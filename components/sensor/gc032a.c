#define SENSOR_ADDR 0x21 // slave id
#define PID_ADDR_H  0xf0
#define PID_ADDR_L  0xf1
#define PID_H       0x23
#define PID_L       0x2a

int gc032a_probe(void)
{
    uint8_t id_h = 0;
	uint8_t id_l = 0;
    SCCB_Read(SENSOR_ADDR, PID_ADDR_H, &id_h, 1);
    SCCB_Read(SENSOR_ADDR, PID_ADDR_L, &id_l, 1);
    printf("-----------camera id %04x\r\n", ((id_h<<8) | id_l));

    if ((PID_H == id_h) && (PID_L == id_l)) {
        printf("ID matched\r\n");
        return 0;
    } else {
        printf("NOT matched\r\n");
        return -1;
    }
}

int gc032a_reset(void)
{
    uint8_t rst_reg = 0xfe;
    uint8_t rst_val = 0xa0;
    SCCB_Write(SENSOR_ADDR, rst_reg, &rst_val);
    return 0;
}

int gc032a_setFMT(void)
{
    for (int i = 0; i < sizeof(gc032a_reglist)/sizeof(gc032a_reglist[0]); i++){
       SCCB_Write(SENSOR_ADDR, gc032a_reglist[i][0], (uint8_t*)&gc032a_reglist[i][1]);
    }

    return 0;
}

