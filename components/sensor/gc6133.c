//0X6e
#define SENSOR_ADDR 0x40 // salve address
//#define VER_ADDR 0x21
#define PID_ADDR    0xf0
#define PID         0xba

int gc6133_probe(void)
{
	uint8_t id = 0;
    SCCB_Read(SENSOR_ADDR, PID_ADDR, &id, 1);
    printf("-----------camera id %02x\r\n", id);

    if (PID == id) {
        printf("ID matched\r\n");
        return 0;
    } else {
        printf("NOT matched\r\n");
        return -1;
    }
}

int gc6133_reset(void)
{
    SCCB_Write(SENSOR_ADDR, gc6133_reglist[1][0], (uint8_t*)&gc6133_reglist[1][1]);
    return 0;
}

int gc6133_setFMT(void)
{
    uint8_t value;
    for (int i = 0; i < sizeof(gc6133_reglist)/sizeof(gc6133_reglist[0]); i++){
       SCCB_Write(SENSOR_ADDR, gc6133_reglist[i][0], (uint8_t*)&gc6133_reglist[i][1]);
       if (gc6133_reglist[i][0] == 0x03) {
           SCCB_Read(SENSOR_ADDR, gc6133_reglist[i][0], &value, 1);
           printf("[0x%02x] = S:[0x%02x], R:[0x%02x]\r\n", gc6133_reglist[i][0], gc6133_reglist[i][1], value);
           platform_delay_ms(1);   
       }
#if 0
    
       SCCB_Read(SENSOR_ADDR, gc6133_reglist[i][0], &value, 1);
       if (gc6133_reglist[i][1] != value)
           printf("[0x%02x] = S:[0x%02x], R:[0x%02x]\r\n", gc6133_reglist[i][0], gc6133_reglist[i][1], value);
       platform_delay_ms(1);   
#endif
    }

    return 0;

}

