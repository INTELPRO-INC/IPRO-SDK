static const uint8_t s_blank[FONT_W] = {0, 0, 0, 0, 0};

const uint8_t *font5x7_glyph(char ch)
{
    unsigned c = (unsigned char)ch;

    if (c >= 'a' && c <= 'z') {
        c -= 'a' - 'A';
    }
    if (c < 0x20u || c > 0x5Au) {
        return s_blank;
    }
    return s_glyphs[c - 0x20u];
}
