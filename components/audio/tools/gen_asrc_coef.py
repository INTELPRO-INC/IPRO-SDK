"""Generate src/audio_asrc_coef.c: the polyphase windowed-sinc table of audio_asrc.

  python3 components/audio/tools/gen_asrc_coef.py > components/audio/src/audio_asrc_coef.c

Kernel: sinc at 0.45 x the input rate, Kaiser beta 6, 16 taps, 128 phases
(+1 so a lookup can interpolate between neighbouring phases). Each phase is
rounded to Q15 and its sum forced to exactly 32768, so DC passes at unity
for every fractional position. Response at 16 kHz input: flat to 4 kHz,
-1.8 dB at 6.5 kHz, images >= 9.5 kHz down 64 dB.
"""
import numpy as np

TAPS = 16
HALF = TAPS // 2
PHASES = 128
FC = 0.45
BETA = 6.0


def kernel(tau):
    w = np.i0(BETA * np.sqrt(np.clip(1.0 - (tau / HALF) ** 2, 0.0, None))) / np.i0(BETA)
    return 2.0 * FC * np.sinc(2.0 * FC * tau) * w


def main():
    rows = []
    for p in range(PHASES + 1):
        mu = p / PHASES
        tau = np.arange(TAPS) - (HALF - 1) - mu          # tap j sits at x[n0 - 7 + j]
        h = kernel(tau)
        h /= h.sum()
        q = np.round(h * 32768.0).astype(int)
        q[np.argmax(np.abs(q))] += 32768 - q.sum()       # exact unity DC
        rows.append(q)

    print("/* Generated by tools/gen_asrc_coef.py - do not edit. */")
    print('#include "audio_asrc.h"')
    print()
    print("/* [phase][tap], Q15, phase p = fractional position p/128 */")
    print("const int16_t g_audio_asrc_coef[AUDIO_ASRC_PHASES + 1][AUDIO_ASRC_TAPS] = {")
    for q in rows:
        print("    { " + ", ".join(f"{v:6d}" for v in q) + " },")
    print("};")


if __name__ == "__main__":
    main()
