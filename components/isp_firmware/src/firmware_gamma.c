void gamma_hw_update(void)
{
    isp_set_GAMMA_curve(&gamma_reg);
}

void gamma_init(void)
{

}

void gamma_control(const gamma_curve_t *curve)
{
    memcpy(&gamma_reg.coef, curve->coef, sizeof(isp_gamma_curve_t));
    gamma_hw_update();
}

int gamma_img_update()
{
    gamma_curve_t *curve;
    GAMMA_CURVE_MODE_E mode = 0;

    img_param_sw_get_gamma_curve_mode(&mode);
    if (mode == GAMMA_CURVE_MODE_INVERSE_BT601) {
        gamma_control(&bt601_inverse_lut_257_12bit);
    } else if (mode == GAMMA_CURVE_MODE_INVERSE_BT709) {
        gamma_control(&bt709_inverse_lut_257_12bit);
    } else if (mode == GAMMA_CURVE_MODE_USER_DEFINE) {
        img_param_sw_get_gamma(&curve);
        gamma_control(curve);
    } else {
        return -1;
    }

    return 0;
}

int imgproc_gamma(void)
{
    if (!img_param_sw_get_states(ISP_ADJ_GAMMA)) {
        isp_set_GAMMA_state(DISABLE);
        return -1;
    }

    isp_set_GAMMA_state(ENABLE);
    gamma_img_update();

    return 0;
}

