/**
 * @file test_images.h
 * @brief Test JPEGs built into the sample (generated by host/make_test_jpegs.py).
 */
#ifndef TEST_IMAGES_H
#define TEST_IMAGES_H

#include <stddef.h>
#include <stdint.h>
#include "jdec_rgb.h"

typedef struct {
    const char    *name;
    const char    *what;     /* one-line description */
    const uint8_t *jpg;
    uint32_t       len;
    int            expect;   /* JDEC_OK or the error jdec_probe() must report */
    uint16_t       blk;      /* reference block size in pixels (0: no reference) */
    uint16_t       bw, bh;   /* reference grid size in blocks */
    const uint8_t *ref;      /* bw * bh RGB block means decoded by libjpeg on the host */
    uint32_t       fnv565;   /* FNV-1a of the RGB565 / RGB888 output of a host build */
    uint32_t       fnv888;   /* of the same decoder (0: not decodable) */
} test_image_t;

extern const test_image_t g_test_images[];
extern const unsigned     g_test_image_count;

#endif /* TEST_IMAGES_H */
